def hex_cells(rings: int):
    """Axial coordinates of every hex cell within `rings` of the origin."""
    return [
        (q, r)
        for q in range(-rings, rings + 1)
        for r in range(-rings, rings + 1)
        if max(abs(q), abs(r), abs(q + r)) <= rings
    ]


def hex_center(q: int, r: int, radius: float = 1.0):
    """Pointy-top axial-to-Cartesian conversion."""
    return radius * math.sqrt(3) * (q + r / 2.0), radius * 1.5 * r


def _in_cluster_lattice(dq: int, dr: int, i: int, j: int, n: int) -> bool:
    """True when (dq,dr) is an integer combination of (i,j) and (-j,i+j)."""
    a = (i + j) * dq + j * dr
    b = -j * dq + i * dr
    return a % n == 0 and b % n == 0


def frequency_groups(cells, i: int, j: int, n: int) -> dict:
    """Assign each cell to one of N frequency groups.

    Groups are the cosets of the cluster lattice generated by the tiling vectors
    (i,j) and (-j,i+j). The first (nearest-origin) cell of each coset becomes the
    group representative, so same-group cells repeat exactly at the reuse distance.
    """
    ordered = sorted(cells, key=lambda c: hex_center(*c)[0] ** 2 + hex_center(*c)[1] ** 2)
    reps: list[tuple[int, int]] = []
    labels: dict = {}
    for q, r in ordered:
        for idx, (rq, rr) in enumerate(reps):
            if _in_cluster_lattice(q - rq, r - rr, i, j, n):
                labels[(q, r)] = idx
                break
        else:
            reps.append((q, r))
            labels[(q, r)] = len(reps) - 1
    assert len(reps) == n, f"expected {n} groups, found {len(reps)}"
    return labels


def plot_reuse_layouts() -> list[dict]:
    cmap = plt.get_cmap("tab20")
    fig, axes = plt.subplots(2, 3, figsize=(13.2, 8.4))
    summary = []

    for ax, n in zip(axes.ravel(), N_LIST):
        i, j = CIJ[n]
        rings = int(round(2 * math.sqrt(n))) + 3
        cells = hex_cells(rings)
        labels = frequency_groups(cells, i, j, n)

        for q, r in cells:
            x, y = hex_center(q, r)
            g = labels[(q, r)]
            ax.add_patch(
                RegularPolygon(
                    (x, y),
                    numVertices=6,
                    radius=1.0,
                    orientation=math.pi / 2,
                    facecolor=cmap(g % 20),
                    edgecolor="white",
                    linewidth=0.6,
                    alpha=0.9,
                )
            )
            ax.text(x, y, str(g + 1), ha="center", va="center", fontsize=5.2, color="black")

        q_val = math.sqrt(3 * n)
        ax.set_aspect("equal")
        ax.set_xlim(-rings * 1.8, rings * 1.8)
        ax.set_ylim(-rings * 1.65, rings * 1.65)
        ax.axis("off")
        ax.set_title(f"N = {n}  (i={i}, j={j})   Q = {q_val:.2f}", fontweight="bold")

        summary.append(
            {
                "N": n,
                "i": i,
                "j": j,
                "Q": round(q_val, 4),
                "groups_visible": len(set(labels.values())),
                "cells_drawn": len(cells),
            }
        )

    fig.suptitle(
        "Hexagonal frequency-reuse plans: colour = frequency group (1..N)",
        fontsize=13,
        fontweight="bold",
    )
    fig.subplots_adjust(left=0.02, right=0.98, top=0.92, bottom=0.02, wspace=0.04, hspace=0.10)
    fig.savefig(FIG / "fig31_reuse_layouts.png", bbox_inches="tight")
    plt.close(fig)

    with open(RES / "mp31_reuse_table.csv", "w", encoding="utf-8") as fh:
        fh.write("N,i,j,Q,groups_visible,cells_drawn\n")
        for row in summary:
            fh.write(
                f"{row['N']},{row['i']},{row['j']},{row['Q']:.4f},"
                f"{row['groups_visible']},{row['cells_drawn']}\n"
            )
    return summary


