# Part (b): synthetic RSRP series and handover policies
# ----------------------------------------------------------------------------


def _serving_trend(t: np.ndarray) -> np.ndarray:
    out = np.empty_like(t, dtype=float)
    for k, tt in enumerate(t):
        if tt < 120:
            out[k] = -86.0 - 0.02 * tt
        elif tt < 190:
            out[k] = -88.4 - 0.022 * (tt - 120)
        elif tt < 240:
            out[k] = -89.94 - 0.5 * (tt - 190)
        else:
            out[k] = -114.94 - 0.01 * (tt - 240)
    return out


def _neighbour_trend(t: np.ndarray) -> np.ndarray:
    return -95.0 + 0.05 * t - 0.00008 * t**2


def make_series(n: int = 300, seed: int = 7, speed_scale: float = 1.0):
    """Serving-cell and neighbour RSRP traces (dBm) with random walk + noise."""
    rng = np.random.default_rng(seed)
    t = np.arange(n, dtype=float)
    serving = _serving_trend(t) * 1.0
    neighbour = _neighbour_trend(t) * 1.0

    # Scale the trend component about its starting value to model faster motion.
    if speed_scale != 1.0:
        serving = serving[0] + speed_scale * (serving - serving[0])
        neighbour = neighbour[0] + speed_scale * (neighbour - neighbour[0])

    rw = np.cumsum(rng.normal(0.0, 0.10 * speed_scale, n))
    rw2 = np.cumsum(rng.normal(0.0, 0.10 * speed_scale, n))
    serving += rw + rng.normal(0.0, 0.80, n)
    neighbour += rw2 + rng.normal(0.0, 0.80, n)
    return serving, neighbour


def simulate_policy(
    series: np.ndarray,
    policy: str = "hysteresis_ttt",
    margin: float = 3.0,
    ttt: int = 5,
    bias: np.ndarray | None = None,
    rlf_threshold: float = -105.0,
    target_cell: int = 1,
):
    """Run one handover policy over a (K, n) RSRP matrix.

    policy: 'naive' (margin 0, TTT 1), 'hysteresis' (margin only),
            'hysteresis_ttt' (margin + time-to-trigger).
    bias: optional per-cell offset (dB) subtracted from the threshold; positive
          values make that neighbour easier to hand over to (load balancing).
    """
    k, n = series.shape
    serving = 0
    streak = 0
    serving_hist = np.zeros(n, dtype=int)
    handovers: list[dict] = []
    min_serving = float(series[serving, 0])

    for t in range(n):
        if t > 0:
            others = [c for c in range(k) if c != serving]
            cand = max(others, key=lambda c: series[c, t])
            eff_margin = 0.0 if policy == "naive" else margin
            b = 0.0 if bias is None else float(bias[cand])
            entering = series[cand, t] > series[serving, t] + eff_margin - b

            streak = streak + 1 if entering else 0
            threshold = 1 if policy in ("naive", "hysteresis") else ttt
            if entering and streak >= threshold:
                handovers.append(
                    {
                        "t": t,
                        "from": int(serving),
                        "to": int(cand),
                        "serving_rsrp": round(float(series[serving, t]), 2),
                        "target_rsrp": round(float(series[cand, t]), 2),
                    }
                )
                serving = cand
                streak = 0

        serving_hist[t] = serving
        min_serving = min(min_serving, float(series[serving, t]))

    # Ping-pong: return to a cell that was left less than 30 samples earlier.
    ping_pongs = 0
    last_left: dict[int, int] = {}
    for h in handovers:
        if h["to"] in last_left and h["t"] - last_left[h["to"]] < 30:
            ping_pongs += 1
        last_left[h["from"]] = h["t"]

    return {
        "handovers": handovers,
        "count": len(handovers),
        "ping_pongs": ping_pongs,
        "serving_hist": serving_hist,
        "min_serving_rsrp": round(min_serving, 2),
        "rlf": bool(min_serving < rlf_threshold),
    }


def plot_handover_comparison(a, b, results):
    fig, axes = plt.subplots(3, 1, figsize=(9.6, 8.6), sharex=True)
    t = np.arange(len(a))
    labels = [
        ("Naive (no margin, no TTT)", 0, "#c0392b"),
        ("Hysteresis only (3 dB)", 3, "#e67e22"),
        ("Hysteresis 3 dB + TTT 5 samples", 5, "#1e8449"),
    ]

    for ax, (title, _, color) in zip(axes, labels):
        res = results[title]
        hist = res["serving_hist"]
        # Shade the active serving cell.
        ax.fill_between(t, -130, 0, where=hist == 0, color="#3498db", alpha=0.07, step="post")
        ax.fill_between(t, -130, 0, where=hist == 1, color="#e74c3c", alpha=0.07, step="post")
        ax.plot(t, a, color="#1f4e79", lw=1.4, label="Cell A (original serving)")
        ax.plot(t, b, color="#b03a2e", lw=1.4, label="Cell B (neighbour)")
        for h in res["handovers"]:
            ax.axvline(h["t"], color=color, lw=1.0, ls="--", alpha=0.9)
        ax.axhline(-100, color="grey", lw=1.0, ls=":", label="RLF threshold (-100 dBm)")
        ax.set_ylim(-120, -82)
        ax.set_ylabel("RSRP (dBm)")
        ax.set_title(
            f"{title} - {res['count']} handover{'s' if res['count'] != 1 else ''}"
            + (f" ({res['ping_pongs']} ping-pong)" if res["ping_pongs"] else "")
        )
        ax.legend(loc="upper right", fontsize=7.5, ncol=3, framealpha=0.9)
        ax.set_xlim(0, len(t) - 1)

    axes[-1].set_xlabel("Sample (arbitrary time units)")
    fig.suptitle("Handover decisions on the same synthetic RSRP traces", fontweight="bold")
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    fig.savefig(FIG / "fig31_handover_comparison.png", bbox_inches="tight")
    plt.close(fig)


def plot_sweep(a, b):
    margins = [0, 1, 2, 3, 4, 5, 6, 8, 10, 12]
    ttts = [1, 2, 3, 4, 5, 6, 8, 10, 12, 15, 20]
    counts = np.zeros((len(margins), len(ttts)), dtype=int)
    min_serv = np.zeros_like(counts, dtype=float)
    series = np.vstack([a, b])

    for mi, m in enumerate(margins):
        for ti, k in enumerate(ttts):
            res = simulate_policy(series, "hysteresis_ttt", margin=m, ttt=k)
            counts[mi, ti] = res["count"]
            min_serv[mi, ti] = res["min_serving_rsrp"]

    feasible = min_serv > -100.0
    masked = np.ma.masked_where(~feasible, counts)

    fig, ax = plt.subplots(figsize=(8.6, 4.6))
    im = ax.imshow(masked, cmap="YlGn_r", aspect="auto", vmin=0, vmax=np.max(counts))
    ax.set_xticks(range(len(ttts)), ttts)
    ax.set_yticks(range(len(margins)), margins)
    ax.set_xlabel("TTT length (samples)")
    ax.set_ylabel("Hysteresis margin (dB)")
    ax.set_title("Handover count sweep (crossed-out cells violate RSRP > -100 dBm)")
    for mi in range(len(margins)):
        for ti in range(len(ttts)):
            if feasible[mi, ti]:
                ax.text(ti, mi, str(counts[mi, ti]), ha="center", va="center", fontsize=7.5)
            else:
                ax.text(ti, mi, "X", ha="center", va="center", fontsize=8, color="black")
    fig.colorbar(im, ax=ax, label="Handovers")
    fig.tight_layout()
    fig.savefig(FIG / "fig31_parameter_sweep.png", bbox_inches="tight")
    plt.close(fig)

    best = None
    for mi, m in enumerate(margins):
        for ti, k in enumerate(ttts):
            if feasible[mi, ti]:
                key = (counts[mi, ti], -min_serv[mi, ti])
                if best is None or key < best[0]:
                    best = (key, m, k, counts[mi, ti], min_serv[mi, ti])
    _, bm, bk, bc, bmin = best
    return {
        "margins": margins,
        "ttts": ttts,
        "counts": counts.tolist(),
        "min_serving": np.round(min_serv, 2).tolist(),
        "feasible": feasible.tolist(),
        "best_margin": bm,
        "best_ttt": bk,
        "best_count": int(bc),
        "best_min_serving": round(float(bmin), 2),
    }


def run_three_cell_variant(a, b, seed=11):
    """Lab Task 2: a second neighbour and strongest-cell selection."""
    rng = np.random.default_rng(seed)
    t = np.arange(len(a))
    c = _neighbour_trend(t) - 1.5 + 0.01 * t
    c = c + np.cumsum(rng.normal(0, 0.10, len(t))) + rng.normal(0, 0.8, len(t))
    series = np.vstack([a, b, c])
    out = {}
    for name, pol, m, k in [
        ("naive", "naive", 0, 1),
        ("hysteresis", "hysteresis", 3, 1),
        ("hysteresis_ttt", "hysteresis_ttt", 3, 5),
    ]:
        res = simulate_policy(series, pol, margin=m, ttt=k)
        out[name] = {
            "count": res["count"],
            "ping_pongs": res["ping_pongs"],
            "handovers": res["handovers"],
            "min_serving": res["min_serving_rsrp"],
        }
    return series, out


def plot_high_speed_comparison():
    rows = []
    for scale, label in [(1.0, "Baseline speed"), (2.0, "2x speed"), (4.0, "4x speed")]:
        a, b = make_series(seed=7, speed_scale=scale)
        series = np.vstack([a, b])
        for name, pol, m, k in [
            ("Naive", "naive", 0, 1),
            ("Hysteresis 3 dB", "hysteresis", 3, 1),
            ("Hyst + TTT(3,5)", "hysteresis_ttt", 3, 5),
        ]:
            res = simulate_policy(series, pol, margin=m, ttt=k)
            rows.append(
                {
                    "speed": label,
                    "policy": name,
                    "count": res["count"],
                    "min_serving": res["min_serving_rsrp"],
                }
            )

    fig, ax = plt.subplots(figsize=(8.4, 4.2))
    policies = ["Naive", "Hysteresis 3 dB", "Hyst + TTT(3,5)"]
    speeds = ["Baseline speed", "2x speed", "4x speed"]
    width = 0.24
    x = np.arange(len(policies))
    colors = ["#4c72b0", "#dd8452", "#55a868"]
    for idx, sp in enumerate(speeds):
        vals = [next(r["count"] for r in rows if r["speed"] == sp and r["policy"] == p) for p in policies]
        ax.bar(x + (idx - 1) * width, vals, width, label=sp, color=colors[idx])
        for xi, v in zip(x + (idx - 1) * width, vals):
            ax.text(xi, v + 0.3, str(v), ha="center", fontsize=7)
    ax.set_xticks(x, policies)
    ax.set_ylabel("Handovers")
    ax.set_title("Effect of device speed on the same tuned parameters")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(FIG / "fig31_speed_effect.png", bbox_inches="tight")
    plt.close(fig)
    return rows


def main():
    reuse = plot_reuse_layouts()

    a, b = make_series(seed=7)
    series = np.vstack([a, b])
    results = {
        "Naive (no margin, no TTT)": simulate_policy(series, "naive"),
        "Hysteresis only (3 dB)": simulate_policy(series, "hysteresis", margin=3),
        "Hysteresis 3 dB + TTT 5 samples": simulate_policy(series, "hysteresis_ttt", margin=3, ttt=5),
    }
    plot_handover_comparison(a, b, results)

    sweep = plot_sweep(a, b)

    # Biased/load-balancing offset (Lab Task 5): make Cell B 2 dB easier to enter.
    biased = simulate_policy(series, "hysteresis_ttt", margin=3, ttt=5, bias=np.array([0.0, 2.0]))
    unbiased = results["Hysteresis 3 dB + TTT 5 samples"]

    _, three = run_three_cell_variant(a, b)
    speed_rows = plot_high_speed_comparison()

    handover_table = [
        {
            "configuration": name,
            "handovers": res["count"],
            "ping_pongs": res["ping_pongs"],
            "min_serving_rsrp": res["min_serving_rsrp"],
            "first_handover": res["handovers"][0]["t"] if res["handovers"] else None,
        }
        for name, res in results.items()
    ]
    with open(RES / "mp31_handover_table.csv", "w", encoding="utf-8") as fh:
        fh.write("configuration,handovers,ping_pongs,min_serving_rsrp,first_handover\n")
        for row in handover_table:
            fh.write(
                f"\"{row['configuration']}\",{row['handovers']},{row['ping_pongs']},"
                f"{row['min_serving_rsrp']},{row['first_handover']}\n"
            )

    payload = {
        "reuse": reuse,
        "handover": handover_table,
        "first_handovers": {k: v["handovers"][:10] for k, v in results.items()},
        "sweep": sweep,
        "bias": {
            "unbiased_count": unbiased["count"],
            "biased_count": biased["count"],
            "unbiased_first": unbiased["handovers"][0]["t"] if unbiased["handovers"] else None,
            "biased_first": biased["handovers"][0]["t"] if biased["handovers"] else None,
        },
        "three_cell": three,
        "speed": speed_rows,
    }
    with open(RES / "mp31_results.json", "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2)

    print("Reuse table:")
    for row in reuse:
        print(f"  N={row['N']:2d}  Q={row['Q']:.3f}  groups={row['groups_visible']}")
    print("\nHandover table:")
    for row in handover_table:
        print(
            f"  {row['configuration']:38s} handovers={row['handovers']:3d} "
            f"ping-pong={row['ping_pongs']:2d} min_serving={row['min_serving_rsrp']} dBm"
        )
    print("\nSweep best:", sweep["best_margin"], "dB /", sweep["best_ttt"], "samples ->", sweep["best_count"])
    print("Bias:", payload["bias"])
    print("Three-cell:", {k: (v["count"], v["ping_pongs"]) for k, v in three.items()})


if __name__ == "__main__":
    main()
