MP33_COMPARISON = (
    "Both policies use the same A→B→C traces but different decision logic. The naive policy hands "
    "over whenever a neighbour is even fractionally stronger. Because the traces are within 1–2 dB "
    "of each other for roughly thirty samples around each crossing, measurement noise repeatedly "
    "reverses the ranking: six handovers, four of which return to a cell left within the previous 30 "
    "samples, which is genuine ping-pong. The tuned policy requires the neighbour to exceed the "
    "serving cell by 3 dB for five consecutive samples. It performs exactly the two intended "
    "handovers (A→B at sample 101 and B→C at sample 314) with no ping-pong, and its mean serving "
    "RSRP is essentially unchanged (−76.45 versus −76.24 dBm). The price is a later decision: its "
    "minimum serving RSRP is 2.4 dB lower than the naive policy's (−95.6 versus −93.3 dBm), because "
    "a device that waits five samples continues to move away from the serving cell.\n"
    "The deep-fade stress case exposes the risk of over-tuning. When cell B fades by up to 36 dB "
    "around sample 244, the naive policy reacts within one sample and hands over to C at sample 242, "
    "so it records no radio-link failure. The tuned policy is still waiting for its five-sample TTT "
    "when B falls to −105.7 dBm, below the −105 dBm RLF threshold, so the connection fails, returns "
    "to Idle and re-accesses through RACH to C. As the fade clears, B is re-selected at sample 257 "
    "and C again at 314. This is exactly the too-late-handover failure that the RLF path exists to "
    "catch. The experiment shows that hysteresis and TTT are complementary but must be dimensioned "
    "against the fastest expected fade: the margin controls ping-pong, the TTT suppresses short noise "
    "excursions, and the RLF threshold caps the waiting time. A practical policy would use a "
    "time-based TTT (for example 160–320 ms), a 2–4 dB margin, a release threshold derived from the "
    "link budget, and a short blacklist for a failed cell to avoid immediate re-selection thrash."
)


