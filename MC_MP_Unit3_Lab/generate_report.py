def section_conclusion(document):
    document.add_page_break()
    document.add_heading("5. Discussion and Conclusion", level=1)
    add_para(
        document,
        "The three mini-projects form a coherent chain. Frequency reuse fixes the geometry: Q = √(3N) "
        "grows slowly with N, while the number of channels per cell falls as 1/N, so every increase "
        "in reuse distance is paid for in capacity. The handover simulations show that the same "
        "trade-off appears in time rather than space: a decision that reacts to every measurement "
        "noise spike (naive) produces ping-pong, while a decision that waits (hysteresis + TTT) "
        "suppresses it but can arrive too late. The capacity tool makes the spatial trade-off "
        "quantitative and shows why operators stop reducing N once it is small and turn to cell "
        "splitting and sectoring instead: those levers add capacity without further shrinking the "
        "cluster. The FSM then places the handover decision inside the wider connection lifecycle, "
        "where RACH and radio-link failure determine whether a decision is merely suboptimal or "
        "actually disruptive."
    )
    add_para(
        document,
        "The measured results support four conclusions. First, N = 7 is a sound default for the "
        "studied geometry: Q = 4.58 and the estimated 18.7 dB SIR are adequate, while N = 3 or 4 is "
        "only viable with sectoring or interference coordination. Second, a 3 dB hysteresis alone is "
        "not sufficient: in the trace it fired on a noise spike at sample 133, 64 samples before the "
        "genuine transition; the five-sample TTT was needed to eliminate that false trigger. Third, "
        "over-tuning is a real failure mode: margin/TTT combinations that reduce the handover count "
        "to one can push the serving RSRP below the −100 dBm floor (up to −113.9 dBm in the sweep), "
        "and the FSM shows the same effect producing an RLF at −105.7 dBm. Fourth, sectoring is the "
        "cheapest capacity lever in this planning exercise: it gives 1.77× capacity at the same SIR "
        "estimate by allowing N = 4 instead of N = 7, without new sites."
    )
    add_para(
        document,
        "The main limitations are the simplified propagation model (no terrain, antenna patterns or "
        "correlated shadowing between cells), the SIR approximation based on six equal-power "
        "interferers, the one-sample handover execution, and the use of traffic channels rather than "
        "Erlang capacity. The hexagonal layouts are also drawn without wrap-around, so edge cells see "
        "fewer neighbours than an infinite plan. These simplifications do not change the direction of "
        "any conclusion, but they mean the absolute SIR and capacity numbers should be treated as "
        "planning estimates. Natural extensions are an Erlang-B blocking calculation, a wrap-around "
        "hexagonal grid, a time-based TTT in milliseconds, sector-level state machines with "
        "inter-sector handovers, and a load-aware neighbour selection policy."
    )


